    private static final Map<String, String> EXACT = new HashMap<>();
    /** Messages built from a fixed start and a variable end: the start is translated, the end goes through {@link #fr}. */
    private static final String[][] PREFIXES;
    private static final Pattern[] RULE_PATTERNS;
    private static final String[] RULE_REPLACEMENTS;
    private static final Pattern NEAREST_GYM = Pattern.compile("Nearest gym: (.*) \\((\\d+)m\\)", Pattern.DOTALL);

    static String fr(String text) {
        if (text == null || text.isEmpty()) return text;
        String hit = EXACT.get(text);
        if (hit != null) return hit;
        Matcher nearest = NEAREST_GYM.matcher(text);
        if (nearest.matches()) return "Arène la plus proche : " + fr(nearest.group(1)) + " (" + nearest.group(2) + " m)";
        for (int i = 0; i < RULE_PATTERNS.length; i++) {
            Matcher match = RULE_PATTERNS[i].matcher(text);
            if (match.matches()) return match.replaceFirst(RULE_REPLACEMENTS[i]);
        }
        for (String[] prefix : PREFIXES) {
            if (text.length() > prefix[0].length() && text.startsWith(prefix[0]))
                return prefix[1] + fr(text.substring(prefix[0].length()));
        }
        return text;
    }

    private static void put(String... pairs) {
        for (int i = 0; i + 1 < pairs.length; i += 2) EXACT.put(pairs[i], pairs[i + 1]);
    }

